-- =========================================================
-- SafeHaven: Google (OAuth) onboarding, permanent roles and
-- public Parent / Child IDs.
--
-- Why: handle_new_user() used to raise when sign-up metadata had no role.
-- Email/password sign-ups send the role in that metadata, but OAuth
-- providers such as Google cannot, so every Google sign-up failed with
-- "Database error saving new user".
--
-- New model
--   * Email/password sign-ups: unchanged. Role is still required in the
--     sign-up metadata and the profile is created by the trigger.
--   * OAuth sign-ups: the auth user is created WITHOUT a profile. A user
--     without a profile is "pending onboarding" and has no access to any
--     family data (every policy and RPC needs a profile/role).
--   * complete_onboarding(role, name) creates the profile exactly once.
--     After that the role and public ID can never change (trigger below).
--   * Every profile gets a public display ID (P-XXXX-XXXX for guardians,
--     C-XXXX-XXXX for children), separate from the internal auth UUID.
--     There is no lookup-by-ID function: an ID alone never links accounts
--     or reveals anything. Linking still needs a one-time invite code.
-- =========================================================

-- ---------------------------------------------------------
-- Public display IDs
-- ---------------------------------------------------------

create function public.generate_public_id(p_role public.user_role)
returns text
language plpgsql volatile set search_path = '' as $$
declare
  alphabet constant text := 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789'; -- 32 symbols: no modulo bias, no 0/O/1/I
  raw bytea := extensions.gen_random_bytes(8);
  c text := '';
begin
  for i in 0..7 loop
    c := c || substr(alphabet, (get_byte(raw, i) % 32) + 1, 1);
  end loop;
  return (case p_role when 'parent' then 'P' else 'C' end) || '-' || left(c, 4) || '-' || right(c, 4);
end;
$$;

alter table public.profiles add column public_id text;

-- Backfill existing accounts (retry on the astronomically unlikely collision)
do $$
declare
  p record;
  candidate text;
begin
  for p in select id, role from public.profiles where public_id is null loop
    loop
      candidate := public.generate_public_id(p.role);
      exit when not exists (select 1 from public.profiles where public_id = candidate);
    end loop;
    update public.profiles set public_id = candidate where id = p.id;
  end loop;
end;
$$;

alter table public.profiles alter column public_id set not null;
alter table public.profiles add constraint profiles_public_id_key unique (public_id);
alter table public.profiles add constraint profiles_public_id_format
  check (public_id ~ '^[PC]-[A-HJ-NP-Z2-9]{4}-[A-HJ-NP-Z2-9]{4}$');
alter table public.profiles add constraint profiles_public_id_matches_role
  check ((role = 'parent' and public_id like 'P-%') or (role = 'child' and public_id like 'C-%'));

-- IDs are always generated by the database, never taken from the caller
create function public.assign_profile_public_id() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  candidate text;
begin
  loop
    candidate := public.generate_public_id(new.role);
    exit when not exists (select 1 from public.profiles where public_id = candidate);
  end loop;
  new.public_id := candidate;
  return new;
end;
$$;

create trigger profiles_assign_public_id before insert on public.profiles
  for each row execute function public.assign_profile_public_id();

-- Role and public ID are permanent once the profile exists, for every caller
-- (column grants already stop clients; this also stops buggy server code)
create function public.protect_profile_identity() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.id is distinct from old.id
     or new.role is distinct from old.role
     or new.public_id is distinct from old.public_id then
    raise exception 'immutable_identity: account type and ID cannot be changed' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger profiles_protect_identity before update on public.profiles
  for each row execute function public.protect_profile_identity();

-- ---------------------------------------------------------
-- Sign-up trigger: password sign-ups still require a role;
-- OAuth sign-ups wait for onboarding
-- ---------------------------------------------------------

create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  meta jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  provider text := coalesce(new.raw_app_meta_data ->> 'provider', '');
  password_signup boolean := provider in ('email', 'phone') or coalesce(new.encrypted_password, '') <> '';
  r text := meta ->> 'role';
  name text := btrim(coalesce(meta ->> 'display_name', ''));
begin
  if not password_signup then
    -- OAuth (e.g. Google). Provider metadata is never trusted for the role:
    -- the account stays in onboarding until complete_onboarding() runs.
    return new;
  end if;

  if r is null or r not in ('parent', 'child') then
    raise exception 'invalid_role: sign-up must specify role parent or child' using errcode = '22023';
  end if;
  if name = '' then
    name := split_part(coalesce(new.email, 'User'), '@', 1);
  end if;
  insert into public.profiles (id, role, display_name)
  values (new.id, r::public.user_role, left(name, 60));
  return new;
end;
$$;

-- ---------------------------------------------------------
-- RPC: onboarding
-- ---------------------------------------------------------

-- Creates the caller's profile once. Returns {ok, role, public_id} or
-- {ok:false, error}. Never changes an existing profile.
create function public.complete_onboarding(p_role text, p_display_name text)
returns jsonb
language plpgsql volatile security definer set search_path = '' as $$
declare
  uid uuid := auth.uid();
  existing public.profiles;
  created public.profiles;
  name text := btrim(regexp_replace(coalesce(p_display_name, ''), '[[:cntrl:]]', '', 'g'));
begin
  if uid is null then
    raise exception 'not_authenticated' using errcode = '28000';
  end if;
  if coalesce((auth.jwt() ->> 'is_anonymous')::boolean, false) then
    raise exception 'forbidden: anonymous sessions cannot create an account' using errcode = '42501';
  end if;

  select * into existing from public.profiles where id = uid;
  if found then
    return jsonb_build_object('ok', false, 'error', 'already_onboarded', 'role', existing.role, 'public_id', existing.public_id);
  end if;

  if p_role is null or p_role not in ('parent', 'child') then
    return jsonb_build_object('ok', false, 'error', 'invalid_role');
  end if;
  if char_length(name) not between 1 and 60 then
    raise exception 'invalid_input: display name must be 1-60 characters' using errcode = '22023';
  end if;

  insert into public.profiles (id, role, display_name)
  values (uid, p_role::public.user_role, name)
  on conflict (id) do nothing
  returning * into created;

  if created.id is null then
    -- Lost a race with a parallel call: report what actually exists
    select * into existing from public.profiles where id = uid;
    return jsonb_build_object('ok', false, 'error', 'already_onboarded', 'role', existing.role, 'public_id', existing.public_id);
  end if;

  return jsonb_build_object('ok', true, 'role', created.role, 'public_id', created.public_id);
end;
$$;

-- ---------------------------------------------------------
-- RPC: pending invitations (codes are stored hashed, so only status is returned)
-- ---------------------------------------------------------

create function public.get_link_invite_status()
returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare
  uid uuid := public.require_role('parent');
  inv public.link_invites;
begin
  select * into inv from public.link_invites li
  where li.parent_id = uid and li.redeemed_at is null and li.revoked_at is null and li.expires_at > now()
  order by li.created_at desc limit 1;
  if not found then
    return jsonb_build_object('ok', true, 'open', null);
  end if;
  return jsonb_build_object('ok', true, 'open', jsonb_build_object('created_at', inv.created_at, 'expires_at', inv.expires_at));
end;
$$;

create function public.revoke_link_invite()
returns integer
language plpgsql volatile security definer set search_path = '' as $$
declare
  uid uuid := public.require_role('parent');
  n integer;
begin
  update public.link_invites li set revoked_at = now()
  where li.parent_id = uid and li.redeemed_at is null and li.revoked_at is null;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- ---------------------------------------------------------
-- Function privileges (new functions get EXECUTE for everyone by default)
-- ---------------------------------------------------------

revoke execute on function
  public.generate_public_id(public.user_role),
  public.assign_profile_public_id(),
  public.protect_profile_identity(),
  public.complete_onboarding(text, text),
  public.get_link_invite_status(),
  public.revoke_link_invite()
  from public, anon, authenticated;

grant execute on function
  public.complete_onboarding(text, text),
  public.get_link_invite_status(),
  public.revoke_link_invite()
  to authenticated;
